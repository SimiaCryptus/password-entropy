// Build O(1) rank lookup map
const WORD_RANK_MAP = new Map();
for (let i = 0; i < RANKED_WORDS.length; i++) {
  const w = RANKED_WORDS[i].toLowerCase();
  if (!WORD_RANK_MAP.has(w)) {
    WORD_RANK_MAP.set(w, i + 1);
  }
}

// Effective dictionary size of a full realistic attacker wordlist (~32,768 words = 15 bits uniform)
export const EFFECTIVE_DICT_SIZE = 32768;
export const UNIFORM_DICT_COST = Math.log2(EFFECTIVE_DICT_SIZE); // 15.0 bits

// Zipf normalization constant H_N for alpha = 0.92, r0 = 3 across EFFECTIVE_DICT_SIZE
const ZIPF_ALPHA = 0.92;
const ZIPF_R0 = 3;
let ZIPF_NORM = 0;
for (let r = 1; r <= EFFECTIVE_DICT_SIZE; r++) {
  ZIPF_NORM += 1 / Math.pow(r + ZIPF_R0, ZIPF_ALPHA);
}

/**
 * Computes Zipfian bit-cost for a word at rank r:
 * P(r) = (1 / (r + r0)^alpha) / ZIPF_NORM
 * Rank 1 ("password") costs ~6.1 bits; Rank 50 costs ~9.2 bits; Rank 1000 costs ~12.8 bits.
 * @param {number} rank
 * @returns {number}
 */
export function getZipfWordCost(rank) {
  const p = (1 / Math.pow(rank + ZIPF_R0, ZIPF_ALPHA)) / ZIPF_NORM;
  return -Math.log2(p);
}

/**
 * Looks up a lowercase word in the dictionary
 * @param {string} word
 * @returns {null | { word: string, rank: number, zipfBits: number, uniformBits: number }}
 */
export function lookupWord(word) {
  const w = word.toLowerCase();
  const rank = WORD_RANK_MAP.get(w);
  if (!rank) return null;

  return {
    word: w,
    rank,
    zipfBits: getZipfWordCost(rank),
    uniformBits: UNIFORM_DICT_COST
  };
}

/**
 * Returns an array of top words for fuzzy edit distance comparison or passphrase generation
 * @param {number} [limit=350]
 * @returns {Array<{ word: string, rank: number }>}
 */
export function getTopDictionaryWords(limit = 350) {
  const list = [];
  for (const [word, rank] of WORD_RANK_MAP.entries()) {
    if (word.length >= 4) {
      list.push({ word, rank });
      if (list.length >= limit) break;
    }
  }
  return list;
}

/**
 * Picks random words from the dictionary to generate a high-MDL passphrase
 * @param {number} [count=4]
 * @returns {string[]}
 */
export function samplePassphraseWords(count = 4) {
  const entries = Array.from(WORD_RANK_MAP.keys()).filter(w => w.length >= 5 && w.length <= 8);
  const chosen = [];
  const cryptoObj = globalThis.crypto;

  for (let i = 0; i < count; i++) {
    let idx;
    if (cryptoObj && cryptoObj.getRandomValues) {
      const arr = new Uint32Array(1);
      cryptoObj.getRandomValues(arr);
      idx = arr[0] % entries.length;
    } else {
      idx = Math.floor(Math.random() * entries.length);
    }
    chosen.push(entries[idx]);
  }
  return chosen;
}